def build_toc():
    """把 RAW 列表展开为 fitz 要求的 (level, title, pdf_page) 平面列表，
    并在每个 本节习题精选 / 答案与解析 下追加四级书签 一、单项选择题。
    注意：'目录' 本身在 PDF 第 1 页，不使用印刷页码偏移。"""
    result = []
    for level, title, page in TOC_RAW:
        pdf_page = 1 if title == "目   录" else p(page)
        result.append((level, title, pdf_page))
        if "本节习题精选" in title or "答案与解析" in title:
            result.append((level + 1, "一、单项选择题", pdf_page))
    return result


def main():
    if not os.path.exists(BACKUP_PATH):
        shutil.copy2(PDF_PATH, BACKUP_PATH)
        print(f"已备份原文件: {BACKUP_PATH}")
    else:
        print(f"备份已存在: {BACKUP_PATH}")

    doc = fitz.open(PDF_PATH)
    old_toc = doc.get_toc()
    print(f"原书签数: {len(old_toc)}")

    new_toc = build_toc()
    doc.set_toc(new_toc)

    # 保存（增量更新，保留原有内容）
    doc.save(PDF_PATH, incremental=True, encryption=fitz.PDF_ENCRYPT_KEEP)
    doc.close()

    # 验证
    doc = fitz.open(PDF_PATH)
    verify = doc.get_toc()
    print(f"新书签数: {len(verify)}")
    for level, title, page in verify[:15]:
        print(f"  {'  ' * (level - 1)}{level} {title} -> {page}")
    print("  ...")
    for level, title, page in verify[-5:]:
        print(f"  {'  ' * (level - 1)}{level} {title} -> {page}")
    doc.close()


if __name__ == "__main__":
    main()
